# https://github.com/ollama/ollama-python

import ollama
from newspaper import Article

class OllamaAI:
    
    @staticmethod
    def aiAnswers(prompt):
        # "gemma3:4b" model to generate a natural language answer to a user prompt
        model = "gemma3:4b"
        
        # Append instruction to generate a simple paragraph
        prompt = prompt + ". In a simple paragraph"
        
        # Send the prompt to Ollama chat model
        response = ollama.chat(
            model=model,
            messages=[
                {"role": "user", "content": prompt}
            ],
        )
        
        # Return the generated answer text
        return response["message"]["content"]
    
    @staticmethod
    def summariseNewsArticle(link):
        # "granite3.1-moe:1b" model to summarise a news article
        model = "granite3.1-moe:1b"
        
        # Download and parse the article text from the provided URL
        article = Article(link, language="en")
        article.download()
        article.parse()
        
        # Prepare prompt for the AI summarisation
        prompt = "Summarise the following article clearly and completely and end with a full sentence, explaining key economic changes and predict their impact on everyday life.\n\n" + article.text
        
        # Send the prompt to Ollama chat model with a limit of 300 tokens for prediction
        response = ollama.chat(
            model=model,
            messages=[
                {"role": "user", "content": prompt}
            ]
        )
        
        # Return the summary generated by the AI
        return response["message"]["content"]